import { describe, expect, it, vi } from 'vitest';
import type { AppDb } from '@core/services/app-db/node/db';
import {
  autoTitleTaskFromPrompt,
  deriveTaskTitleFromPrompt,
  ensureUniqueDisplayTaskTitle,
  isAutoGeneratedTaskName,
} from './auto-title-task';

const renameTaskMock = vi.fn();

vi.mock('../../node/operations/renameTask', () => ({
  renameTask: (...args: unknown[]) => renameTaskMock(...args),
}));

describe('isAutoGeneratedTaskName', () => {
  it('detects human-id random placeholders and default names', () => {
    expect(isAutoGeneratedTaskName('thick-guests-scream')).toBe(true);
    expect(isAutoGeneratedTaskName('plenty-peas-mix')).toBe(true);
    expect(isAutoGeneratedTaskName('eighty-maps-draw')).toBe(true);
    expect(isAutoGeneratedTaskName('cute-ideas-post')).toBe(true);
    expect(isAutoGeneratedTaskName('cute-ideas-post-2')).toBe(true);
    expect(isAutoGeneratedTaskName('Yeni görev')).toBe(true);
    expect(isAutoGeneratedTaskName('Yeni görev (3)')).toBe(true);
    expect(isAutoGeneratedTaskName('Yeni sohbet')).toBe(true);
    expect(isAutoGeneratedTaskName('Yeni sohbet (2)')).toBe(true);
    expect(isAutoGeneratedTaskName('New task')).toBe(true);
    expect(isAutoGeneratedTaskName('New chat (4)')).toBe(true);
    expect(isAutoGeneratedTaskName('')).toBe(true);
  });

  it('does not treat user-chosen task names as placeholders', () => {
    expect(isAutoGeneratedTaskName('fix-auth-bug')).toBe(false);
    expect(isAutoGeneratedTaskName('Twilio Giriş Hatası Düzeltme')).toBe(false);
    expect(isAutoGeneratedTaskName('apk-arayuz')).toBe(false);
    expect(isAutoGeneratedTaskName('proj-123-oauth')).toBe(false);
  });
});

describe('deriveTaskTitleFromPrompt', () => {
  it('extracts clean Turkish topic titles and strips greetings and hidden context', () => {
    expect(
      deriveTaskTitleFromPrompt(
        '<orkestra_context>gizli sistem bağlamı</orkestra_context>\n\nkanka bu bölümde sağ tık yapınca aktif sohbeti terminale çevirebiliyorduk. terminalden de normal sohbete.'
      )
    ).toBe('Sağ Tık Yapınca Aktif Sohbeti Terminale');

    expect(deriveTaskTitleFromPrompt('Selam, lütfen Twilio giriş hatasını düzelt')).toBe(
      'Twilio Giriş Hatasını Düzelt'
    );

    expect(deriveTaskTitleFromPrompt('proje analizi ve değerlendirme yap')).toBe(
      'Proje Analizi ve Değerlendirme Yap'
    );
  });

  it('preserves uppercase technical acronyms and handles English prompts', () => {
    expect(deriveTaskTitleFromPrompt('Antigravity native SSH bağlantısı ekle')).toBe(
      'Antigravity Native SSH Bağlantısı Ekle'
    );
    expect(deriveTaskTitleFromPrompt('please add dark mode toggle to settings page')).toBe(
      'Add Dark Mode Toggle to Settings Page'
    );
  });

  it('returns null for slash commands or empty input', () => {
    expect(deriveTaskTitleFromPrompt('/clear')).toBeNull();
    expect(deriveTaskTitleFromPrompt('   \n  ')).toBeNull();
    expect(deriveTaskTitleFromPrompt('```ts\nconst x = 1;\n```')).toBeNull();
  });
});

describe('ensureUniqueDisplayTaskTitle', () => {
  it('appends a numeric suffix when a sibling task shares the same title', () => {
    expect(
      ensureUniqueDisplayTaskTitle('Twilio Giriş Hatası', ['twilio giriş hatası', 'Diğer Görev'])
    ).toBe('Twilio Giriş Hatası (2)');
    expect(
      ensureUniqueDisplayTaskTitle('Twilio Giriş Hatası', [
        'Twilio Giriş Hatası',
        'Twilio Giriş Hatası (2)',
      ])
    ).toBe('Twilio Giriş Hatası (3)');
  });
});

describe('autoTitleTaskFromPrompt', () => {
  function mockDb(currentName: string | null, siblingNames: string[] = []): AppDb {
    let call = 0;
    return {
      select: vi.fn(() => ({
        from: vi.fn(() => ({
          where: vi.fn(() => {
            call += 1;
            if (call === 1) {
              return {
                limit: vi.fn(async () =>
                  currentName === null ? [] : [{ id: 'task-1', name: currentName }]
                ),
              };
            }
            return Promise.resolve(siblingNames.map((name) => ({ name })));
          }),
        })),
      })),
    } as unknown as AppDb;
  }

  it('renames a task with a placeholder name based on the first prompt', async () => {
    renameTaskMock.mockReset();
    renameTaskMock.mockResolvedValue({
      success: true,
      data: { task: { id: 'task-1', name: 'Twilio Giriş Hatasını Düzelt' } },
    });
    const db = mockDb('thick-guests-scream', ['Başka Görev']);

    const renamed = await autoTitleTaskFromPrompt(
      db,
      'proj-1',
      'task-1',
      'kanka Twilio giriş hatasını düzelt'
    );

    expect(renamed).toBe('Twilio Giriş Hatasını Düzelt');
    expect(renameTaskMock).toHaveBeenCalledWith(
      db,
      'proj-1',
      'task-1',
      'Twilio Giriş Hatasını Düzelt'
    );
  });

  it('does not overwrite a user-chosen task name', async () => {
    renameTaskMock.mockReset();
    const db = mockDb('Özel Görev Adım');

    const renamed = await autoTitleTaskFromPrompt(
      db,
      'proj-1',
      'task-1',
      'Twilio giriş hatasını düzelt'
    );

    expect(renamed).toBeNull();
    expect(renameTaskMock).not.toHaveBeenCalled();
  });

  it('recognizes Yeni sohbet / New chat placeholders and strips casual Turkish openings', async () => {
    expect(isAutoGeneratedTaskName('Yeni sohbet')).toBe(true);
    expect(isAutoGeneratedTaskName('New chat')).toBe(true);
    expect(deriveTaskTitleFromPrompt('kanka bide ses kaydı çalışmıyor onu düzelt')).toBe(
      'Ses Kaydı Çalışmıyor Onu Düzelt'
    );

    renameTaskMock.mockReset();
    renameTaskMock.mockResolvedValue({
      success: true,
      data: { task: { id: 'task-1', name: 'Ses Kaydı Çalışmıyor Onu Düzelt' } },
    });
    const db = mockDb('Yeni sohbet', []);

    const renamed = await autoTitleTaskFromPrompt(
      db,
      '__orkestra_free_chats__',
      'task-1',
      'kanka bide ses kaydı çalışmıyor onu düzelt'
    );

    expect(renamed).toBe('Ses Kaydı Çalışmıyor Onu Düzelt');
    expect(renameTaskMock).toHaveBeenCalledWith(
      db,
      '__orkestra_free_chats__',
      'task-1',
      'Ses Kaydı Çalışmıyor Onu Düzelt'
    );
  });

  it('renames a task with a numbered placeholder such as Yeni sohbet (2)', async () => {
    renameTaskMock.mockReset();
    renameTaskMock.mockResolvedValue({
      success: true,
      data: { task: { id: 'task-2', name: 'Ayarlar Sayfası Açılmıyor' } },
    });
    const db = mockDb('Yeni sohbet (2)', ['Yeni sohbet']);

    const renamed = await autoTitleTaskFromPrompt(
      db,
      'proj-1',
      'task-2',
      'ayarlar sayfası açılmıyor'
    );

    expect(renamed).toBe('Ayarlar Sayfası Açılmıyor');
    expect(renameTaskMock).toHaveBeenCalledWith(
      db,
      'proj-1',
      'task-2',
      'Ayarlar Sayfası Açılmıyor'
    );
  });
});
