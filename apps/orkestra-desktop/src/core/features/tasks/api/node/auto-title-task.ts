const MAX_AUTO_TITLE_LENGTH = 54;
const MAX_AUTO_TITLE_WORDS = 7;
/** Başlık modeli bu süre içinde yanıt vermezse sezgisel başlığa düşülür. */
const GENERATED_TITLE_TIMEOUT_MS = 8_000;

const ADJECTIVES = new Set(adjectives.map((w) => w.toLowerCase()));
const NOUNS = new Set(nouns.map((w) => w.toLowerCase()));
const VERBS = new Set(verbs.map((w) => w.toLowerCase()));

const DEFAULT_PLACEHOLDER_NAMES = new Set([
  'yeni görev',
  'yeni sohbet',
  'new task',
  'new chat',
  'untitled task',
  'untitled chat',
]);

// Kısa Türkçe/İngilizce bağlaçlar ve edatlar (ilk kelime değilse küçük kalır).
const LOWERCASE_CONNECTORS = new Set([
  've',
  'ile',
  'veya',
  'ya',
  'da',
  'de',
  'için',
  'gibi',
  'and',
  'or',
  'of',
  'to',
  'in',
  'on',
  'for',
  'with',
  'the',
  'a',
  'an',
]);

// Mesaj başında konuyu özetlemeyen selamlama / konuşma dolguları (devamında anlamlı metin varsa kırpılır).
const LEADING_FILLER_PATTERNS = [
  /^(?:kanka|kanki|knk|aga|hocam|dostum|reis|kardeşim|abi|usta|cano|canım|moruk|bro|selamlar|selam|merhabalar|merhaba|slm|mrb|hey|eyy|ey|naber|nasılsın|hi|hello|yo)\b[\s,.:;!-]*/i,
  /^(?:lütfen|lutfen|please|pls|acaba|baksana|bak|şimdi|simdi|ya|bi|bir|bide|bi\s+de|bir\s+de|birde|şey|sey|hani|peki|tamam|şu|su|bu\s+bölümde|burada|şurada)\b[\s,.:;!-]*/i,
  /^(?:can\s+you|could\s+you|would\s+you|please\s+help\s+me|help\s+me|i\s+want\s+you\s+to|i\s+need\s+you\s+to)\b[\s,.:;!-]*/i,
];

/**
 * Görev adı hâlâ sistemin ürettiği yer tutucu (human-id rastgele 3 kelime, "Yeni görev" veya
 * görevin sohbet sağlayıcılarından birinin varsayılan başlığı "Claude (1)") mi?
 * Kullanıcının elle seçtiği özel adları asla ezmemek için kesin sözlük kontrolü yapar.
 *
 * `providerIds`: görevin sohbetlerinin sağlayıcıları. Eşitleme, görev adını sohbetin varsayılan
 * başlığına ("Claude (1)") çevirdiğinde bu ad da yer tutucu sayılmalıdır; aksi halde ilk istekte
 * otomatik başlık hiç verilmez.
 */
export function isAutoGeneratedTaskName(
  name: string | null | undefined,
  providerIds: Iterable<string | null | undefined> = []
): boolean {
  const trimmed = (name ?? '').trim();
  if (!trimmed) return true;
  if (isDefaultConversationTitle(trimmed, providerIds)) return true;
  const lowered = trimmed.toLocaleLowerCase('tr-TR');
  const normalizedPlaceholder = lowered.replace(/\s*\(\d+\)$/, '').trim();
  if (DEFAULT_PLACEHOLDER_NAMES.has(normalizedPlaceholder)) return true;

  // human-id biçimi: `<sıfat>-<isim>-<fiil>` (çakışma son eki `-2`..`-99` olabilir).
  const withoutSuffix = trimmed.toLowerCase().replace(/-\d+$/, '');
  const parts = withoutSuffix.split('-');
  if (parts.length !== 3) return false;
  return ADJECTIVES.has(parts[0]!) && NOUNS.has(parts[1]!) && VERBS.has(parts[2]!);
}

function cleanPromptForTitle(raw: string): string {
  let text = raw
    .replace(/<orkestra_context>[\s\S]*?<\/orkestra_context>/g, ' ')
    .replace(/<orkestra_context>[\s\S]*$/, ' ');
  // Kod bloklarını ve gizli XML/HTML sarmalayıcılarını temizle.
  text = text.replace(/```[\s\S]*?```/g, ' ');
  text = text.replace(/<\/?[a-z_][a-z0-9_-]*[^>]*>/gi, ' ');
  // Markdown bağlantılarını görünür metne indirge, ham URL'leri çıkar.
  text = text.replace(/\[([^\]]+)\]\((?:https?:\/\/|file:\/\/)[^)]+\)/g, '$1');
  text = text.replace(/\bhttps?:\/\/\S+/gi, ' ');
  // Satır içi kod ve biçimlendirme işaretlerini sadeleştir.
  text = text.replace(/`([^`]+)`/g, '$1');
  text = text.replace(/[*_~#>]/g, ' ');
  return text;
}

function stripLeadingFillers(input: string): string {
  let current = input.trim();
  for (let pass = 0; pass < 4; pass++) {
    let changed = false;
    for (const pattern of LEADING_FILLER_PATTERNS) {
      const next = current.replace(pattern, '').trim();
      // Kırpma sonucu en az 2 anlamlı kelime kalıyorsa uygula.
      if (next !== current && next.split(/\s+/).filter(Boolean).length >= 2) {
        current = next;
        changed = true;
      }
    }
    if (!changed) break;
  }
  return current;
}

function formatWord(word: string, index: number): string {
  if (!word) return word;
  // Tamamı büyük kısaltmaları veya karma teknik tanımlayıcıları (APK, SSH, GitHub, iOS) koru.
  if (/[A-ZÇĞİÖŞÜ]/.test(word.slice(1)) || (/^[A-Z0-9]{2,}$/.test(word) && /[A-Z]/.test(word))) {
    return word;
  }
  const lower = word.toLocaleLowerCase('tr-TR');
  if (index > 0 && LOWERCASE_CONNECTORS.has(lower)) {
    return lower;
  }
  const first = word.charAt(0).toLocaleUpperCase('tr-TR');
  return first + word.slice(1);
}

/**
 * Kullanıcının ilk isteğinden kısa, okunaklı bir konu başlığı türetir.
 * Yalnızca slash komutu veya anlamsız noktalama içeren girdilerde `null` döner.
 */
export function deriveTaskTitleFromPrompt(prompt: string): string | null {
  const cleaned = cleanPromptForTitle(prompt);
  // İlk anlamlı satırı seç (boş satırları ve yalnız slash komutlarını atla).
  const candidateLine = cleaned
    .split(/\r?\n/)
    .map((line) => line.replace(/^[\s\-*•\d.)]+/, '').trim())
    .find((line) => line.length > 0 && !/^\/[a-z0-9_-]+$/i.test(line));
  if (!candidateLine) return null;

  // İlk cümleyi al (kısaltma/dosya adındaki noktaları bölmemek için `. ` veya satır sonu).
  const firstSentence = candidateLine.split(/(?:[.!?]+(?:\s+|$))|(?:\s+[—–]\s+)/)[0]?.trim() ?? '';
  const withoutFillers = stripLeadingFillers(firstSentence || candidateLine);
  const normalized = withoutFillers
    .replace(/^["'«»“”‘’([]+|["'«»“”‘’)\],.;:!?]+$/g, '')
    .replace(/\s+/g, ' ')
    .trim();

  if (!normalized || !/[\p{L}\p{N}]/u.test(normalized)) return null;

  const words = normalized.split(' ').filter(Boolean);
  const selected: string[] = [];
  let length = 0;

  for (const rawWord of words) {
    if (selected.length >= MAX_AUTO_TITLE_WORDS) break;
    const word = rawWord.replace(/[,;:]+$/, '');
    if (!word) continue;
    const nextLength = length === 0 ? word.length : length + 1 + word.length;
    if (nextLength > MAX_AUTO_TITLE_LENGTH) {
      if (selected.length === 0) {
        selected.push(word.slice(0, MAX_AUTO_TITLE_LENGTH));
      }
      break;
    }
    selected.push(word);
    length = nextLength;
  }

  if (selected.length === 0) return null;

  const title = selected
    .map((word, index) => formatWord(word, index))
    .join(' ')
    .replace(/[,.;:!?]+$/, '')
    .trim();

  return title.length >= 2 ? title : null;
}

/**
 * Yüklenen sohbet geçmişindeki ilk (en eski) boş olmayan kullanıcı mesajı. Geçmişi olan ama hâlâ
 * yer tutucu adlı görevleri (ör. eşitlemenin "Claude (1)" yaptığı eski sohbetler) sohbet
 * açıldığında bir kez adlandırmak için kullanılır.
 */
export function firstUserMessageText(
  turns: ReadonlyArray<{ readonly items: ReadonlyArray<unknown> }>
): string | null {
  for (const turn of turns) {
    for (const item of turn.items) {
      if (typeof item !== 'object' || item === null) continue;
      const candidate = item as { kind?: unknown; role?: unknown; text?: unknown };
      if (
        candidate.kind === 'message' &&
        candidate.role === 'user' &&
        typeof candidate.text === 'string' &&
        candidate.text.trim()
      ) {
        return candidate.text;
      }
    }
  }
  return null;
}

/** Süre dolarsa `null` döner; arka plandaki istek kendi zaman aşımıyla sonlanır. */
async function withTimeout<T>(promise: Promise<T>, timeoutMs: number): Promise<T | null> {
  let timer: ReturnType<typeof setTimeout> | undefined;
  try {
    return await Promise.race([
      promise,
      new Promise<null>((resolve) => {
        timer = setTimeout(() => resolve(null), timeoutMs);
      }),
    ]);
  } finally {
    if (timer !== undefined) clearTimeout(timer);
  }
}

export function ensureUniqueDisplayTaskTitle(
  baseTitle: string,
  existingNames: Iterable<string>
): string {
  const taken = new Set(
    Array.from(existingNames, (name) => name.trim().toLocaleLowerCase('tr-TR')).filter(Boolean)
  );
  const cleanBase = baseTitle.trim().slice(0, 64);
  if (!taken.has(cleanBase.toLocaleLowerCase('tr-TR'))) return cleanBase;

  for (let i = 2; i < 100; i++) {
    const suffix = ` (${i})`;
    const candidate = `${cleanBase.slice(0, 64 - suffix.length)}${suffix}`;
    if (!taken.has(candidate.toLocaleLowerCase('tr-TR'))) return candidate;
  }
  return cleanBase;
}

/**
 * Görev hâlâ otomatik yer tutucu ada sahipse, kullanıcının ilk isteğinden türetilen konu başlığıyla
 * görevi adlandırır. Kullanıcı kendi adını vermişse dokunmaz.
 */
export async function autoTitleTaskFromPrompt(
  db: AppDb,
  projectId: string,
  taskId: string,
  prompt: string,
  generateTitle?: (prompt: string) => Promise<string | null>,
  generateTimeoutMs: number = GENERATED_TITLE_TIMEOUT_MS
): Promise<string | null> {
  const [row] = await db
    .select({ id: tasks.id, name: tasks.name })
    .from(tasks)
    .where(and(eq(tasks.id, taskId), eq(tasks.projectId, projectId), isNull(tasks.deletedAt)))
    .limit(1);
  if (!row) return null;
  if (!isAutoGeneratedTaskName(row.name)) {
    // Sağlayıcı-varsayılan ad ("Claude (1)") yalnızca görevin kendi sohbet sağlayıcılarına göre
    // tanınır; ek sorgu yalnızca ad sözlükteki yer tutuculardan biri değilse yapılır.
    const providerRows = await db
      .select({ provider: conversations.provider })
      .from(conversations)
      .where(eq(conversations.taskId, taskId));
    if (
      !isAutoGeneratedTaskName(
        row.name,
        providerRows.map((r) => r.provider)
      )
    ) {
      return null;
    }
  }

  let derived: string | null = null;
  if (generateTitle) {
    try {
      const generated = await withTimeout(generateTitle(prompt), generateTimeoutMs);
      if (generated && generated.trim().length >= 2) {
        derived = generated.trim().slice(0, MAX_AUTO_TITLE_LENGTH);
      }
    } catch {
      derived = null;
    }
  }
  if (!derived) {
    derived = deriveTaskTitleFromPrompt(prompt);
  }
  if (!derived) return null;

  const siblings = await db
    .select({ name: tasks.name })
    .from(tasks)
    .where(and(eq(tasks.projectId, projectId), ne(tasks.id, taskId), isNull(tasks.deletedAt)));

  const uniqueTitle = ensureUniqueDisplayTaskTitle(
    derived,
    siblings.map((s) => s.name)
  );
  const result = await renameTask(db, projectId, taskId, uniqueTitle);
  return result.success ? result.data.task.name : null;
}

const TURKISH_CHAR_MAP: Readonly<Record<string, string>> = {
  ç: 'c',
  Ç: 'c',
  ğ: 'g',
  Ğ: 'g',
  ı: 'i',
  İ: 'i',
  I: 'i',
  ö: 'o',
  Ö: 'o',
  ş: 's',
  Ş: 's',
  ü: 'u',
  Ü: 'u',
};

const MAX_AUTO_BRANCH_SLUG_LENGTH = 48;

/**
 * Görev başlığından ASCII uyumlu, güvenli bir Git branch adı türetir.
 * Mevcut branch adında slash öneki varsa (ör. `feat/eski-ad`), aynı öneki korur.
 */
export function deriveBranchSlugFromTitle(
  title: string,
  currentBranch?: string | null
): string | null {
  const transliterated = title
    .replace(/[çÇğĞıİIöÖşŞüÜ]/g, (ch) => TURKISH_CHAR_MAP[ch] ?? ch)
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase();

  let slug = transliterated
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, MAX_AUTO_BRANCH_SLUG_LENGTH)
    .replace(/-+$/g, '');

  if (slug.length < 2) return null;

  const trimmedCurrent = currentBranch?.trim() ?? '';
  const slashIndex = trimmedCurrent.lastIndexOf('/');
  if (slashIndex > 0) {
    const prefix = trimmedCurrent.slice(0, slashIndex + 1);
    slug = `${prefix}${slug}`;
  }
  return slug;
}
